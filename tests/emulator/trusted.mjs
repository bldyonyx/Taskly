test('revision, duplicate requests, request-ID reuse and concurrent commands have atomic single effects', async () => {
  assert.equal((await execute(replace(0))).code, 'conflict')
  const command = replace(1, [task('two', true)])
  const results = await Promise.all([execute(command), execute(command)])
  assert.ok(results.every((r) => r.ok))
  assert.equal(results.filter((r) => !r.replayed).length, 1)
  assert.equal((await manifest()).revision, 2)
  assert.equal((await execute({ ...command, payload: { ...command.payload, tasks: [] } })).code, 'idempotency-conflict')
  const competing = await Promise.all([execute(replace(2)), execute(replace(2, [task('other')]))])
  assert.equal(competing.filter((r) => r.ok).length, 1)
  assert.equal(competing.filter((r) => r.code === 'conflict').length, 1)
  // Exact original result is returned even after later commits.
  assert.equal((await execute(command)).revision, 2)
  assert.equal((await manifest()).revision, 3)
})

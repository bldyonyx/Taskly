async function user(name, admission = admitted()) {
  // Only this operator fixture can initialize. The isolated demo database is
  // cleared below; every UID is newly generated by the real Auth emulator.
  const response = await fetch(`http://${AUTH_HOST}/identitytoolkit.googleapis.com/v1/accounts:signUp?key=emulator-only`, {
    method: 'POST', headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ email: `${name}@example.test`, password: 'synthetic-test-password', returnSecureToken: true }),
  })
  assert.equal(response.ok, true)
  const { localId: uid, idToken: token } = await response.json()
  const batch = db.batch()
  batch.set(root(uid, 'lifecycle/state'), { schemaVersion: 1, ownerId: uid, revision: 0, parents: {} })
  batch.set(root(uid, 'trusted/state'), { version: 1, requestCount: 0 })
  if (admission) batch.set(db.doc(`stagingTesters/${uid}`), admission)
  await batch.commit()
  return { uid, token }
}
